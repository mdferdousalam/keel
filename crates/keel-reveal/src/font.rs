/// The rows for `ch`, or a replacement box when it has no glyph.
///
/// Never returns blank for an unknown character. A password containing something this font
/// cannot draw must look wrong on screen, not short.
#[must_use]
pub fn glyph(ch: char) -> &'static [u8; GLYPH_H] {
    const REPLACEMENT: [u8; GLYPH_H] = [
        0x00, 0x00, 0x7e, 0x42, 0x5a, 0x5a, 0x42, 0x5a, 0x5a, 0x42, 0x7e, 0x00, 0x00, 0x00,
    ];
    let code = u32::from(ch);
    if code < u32::from(FIRST) || code > u32::from(LAST) {
        return &REPLACEMENT;
    }
    #[allow(clippy::cast_possible_truncation)]
    let index = (code as u8 - FIRST) as usize;
    GLYPHS.get(index).unwrap_or(&REPLACEMENT)
}
