//! An 8x14 bitmap font for printable ASCII.
//!
//! Hand-built and embedded rather than loaded from a font file, for three reasons that
//! all point the same way.
//!
//! **No font parsing.** A font library is a parser for a complex binary format, and this
//! process is the one that holds a plaintext password in its address space. Adding a
//! parser there buys nothing and widens the attack surface of the component that can least
//! afford it.
//!
//! **No ambiguity.** Passwords are drawn from an 88-character ASCII alphabet and are read
//! aloud, retyped, and transcribed. A fixed-width bitmap face keeps `l`/`1`/`I` and
//! `0`/`O` visibly distinct, which a proportional system font chosen at runtime does not
//! guarantee.
//!
//! **No fallback surprises.** Whatever the OS would have substituted for a missing glyph,
//! it is not substituting here: anything outside printable ASCII is drawn as a visible
//! replacement box, so a character that cannot be rendered is obvious rather than absent.

/// Glyph width in pixels.
pub const GLYPH_W: usize = 8;
/// Glyph height in pixels.
pub const GLYPH_H: usize = 14;

/// First character with a glyph.
pub const FIRST: u8 = 0x20;
/// Last character with a glyph.
pub const LAST: u8 = 0x7e;

